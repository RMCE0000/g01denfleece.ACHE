_FRAMES = (
    "Could you share {topic} with a neighbor, or do you need it?",
    "Would homesteads in your ZIP save money by handling {topic} together?",
    "Could a neighbor use your help with {topic}, or could you use theirs?",
    "What would you trade for {topic}?",
)

TOPICS = tuple(
    _FRAMES[index % len(_FRAMES)].format(topic=topic)
    for index, topic in enumerate(TOPIC_PHRASES)
)


def topic_for(zip_code: str, day: date, *, salt: str = "") -> str:
    """One stable topic for this ZIP and local day."""
    digest = hashlib.sha256(f"{zip_code}|{day.isoformat()}|{salt}".encode()).digest()
    return TOPICS[int.from_bytes(digest[:4], "big") % len(TOPICS)]
